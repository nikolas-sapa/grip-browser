# Fixture registries
# --------------------------------------------------------------------------

# path relative to FIXTURES_DIR -> expected classification stage
NEGATIVE_FIXTURES: dict[str, ChallengeStage] = {
    "neg_plain.html": ChallengeStage.NONE,
    "neg_login_no_captcha.html": ChallengeStage.NONE,
    "neg_captcha_field_only.html": ChallengeStage.NONE,
    "neg_captcha_img_only.html": ChallengeStage.NONE,
    "neg_blog_solve_a_captcha.html": ChallengeStage.NONE,
    "neg_security_check_footer.html": ChallengeStage.NONE,
    "neg_turnstile_docs_snippet.html": ChallengeStage.NONE,
    "neg_carousel_slider.html": ChallengeStage.NONE,
}

POSITIVE_FIXTURES: dict[str, ChallengeStage] = {
    "pos_checkbox_recaptcha.html": ChallengeStage.CHECKBOX,
    "pos_checkbox_hcaptcha.html": ChallengeStage.CHECKBOX,
    "pos_image_grid.html": ChallengeStage.IMAGE_GRID,
    "pos_slider.html": ChallengeStage.SLIDER,
    "pos_text_captcha.html": ChallengeStage.TEXT,
    "pos_invisible.html": ChallengeStage.INVISIBLE,
    "pos_unknown_prose.html": ChallengeStage.UNKNOWN,
}

# path -> (attempted?, expected status if attempted)
SOLVE_FIXTURES: dict[str, str] = {
    "solve_checkbox_success.html": "solved",
    "solve_checkbox_never.html": "timeout",
    "solve_checkbox_zero_size.html": "unsupported",
    "solve_slider_success.html": "solved",
    "solve_slider_never.html": "timeout",
    "solve_slider_no_track.html": "unsupported",
}

# Cloudflare's own published test sitekeys — never a production key.
# https://developers.cloudflare.com/turnstile/troubleshooting/testing/
TURNSTILE_ALWAYS_PASSES = "1x00000000000000000000AA"
TURNSTILE_ALWAYS_FAILS = "2x00000000000000000000AB"


# --------------------------------------------------------------------------
# Result records
# --------------------------------------------------------------------------


@dataclass
class ClassifyRow:
    fixture: str
    source: str
    expected: str
    pure_fn_correct: int = 0
    page_correct: int = 0
    runs: int = 0
    pure_fn_observed: list[str] = field(default_factory=list)
    page_observed: list[str] = field(default_factory=list)


@dataclass
class SolveRow:
    fixture: str
    source: str
    expected_status: str
    runs: int = 0
    attempted: int = 0
    matched_expected: int = 0
    false_solved: int = 0  # claimed solved while fixture state disagrees
    observed_statuses: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)


def _now_tag() -> str:
    return datetime.now(UTC).strftime("%Y%m%d-%H%M%S")


# --------------------------------------------------------------------------
# Classification benchmark
# --------------------------------------------------------------------------


_IFRAME_SRC_RE = re.compile(r'<iframe[^>]+src=["\']([^"\']+)["\']', re.IGNORECASE)


async def run_classification(browser: Browser, base_url: str) -> list[ClassifyRow]:
    rows: list[ClassifyRow] = []
    all_fixtures = {**NEGATIVE_FIXTURES, **POSITIVE_FIXTURES}
    for rel_path, expected in all_fixtures.items():
        html_source = (FIXTURES_DIR / rel_path).read_text(encoding="utf-8")
        # detect_challenge_from_html takes (html, frames) — frames is the list
        # of *frame URLs*, which the real caller gets from Page.getFrameTree,
        # not from parsing <iframe src>. Fixtures encode their signature in
        # the iframe src the same way the frame tree would report it, so
        # extracting src attributes here reproduces what Page.detect_challenge
        # actually sees, instead of testing the pure function against empty
        # frames and calling it a fair comparison.
        frame_srcs = [f"{base_url}/{m}" for m in _IFRAME_SRC_RE.findall(html_source)]
        row = ClassifyRow(fixture=rel_path, source="synthetic-fixture", expected=expected.value)
        for _ in range(N_RUNS):
            row.runs += 1
            # 1. pure function, the same markup + frame URLs, no browser.
            stage = detect_challenge_from_html(html_source, frames=frame_srcs)
            row.pure_fn_observed.append(stage.value)
            if stage is expected:
                row.pure_fn_correct += 1

            # 2. through the real plumbing: served over HTTP, loaded in a
            # real page, frame tree read via CDP.
            page = await browser.open(f"{base_url}/{rel_path}")
            try:
                await asyncio.sleep(0.15)  # let child iframes finish navigating
                page_stage = await page.detect_challenge()
            finally:
                await page.close()
            row.page_observed.append(page_stage.value)
            if page_stage is expected:
                row.page_correct += 1
        rows.append(row)
    return rows


# --------------------------------------------------------------------------
# Solve benchmark (local synthetic fixtures)
# --------------------------------------------------------------------------


async def run_solve(browser: Browser, base_url: str) -> list[SolveRow]:
    rows: list[SolveRow] = []
    for rel_path, expected_status in SOLVE_FIXTURES.items():
        row = SolveRow(
            fixture=rel_path, source="synthetic-fixture", expected_status=expected_status
        )
        for _ in range(N_RUNS):
            row.runs += 1
            page = await browser.open(f"{base_url}/{rel_path}")
            try:
                await asyncio.sleep(0.15)
                stage = await page.detect_challenge()
                if stage is not ChallengeStage.NONE:
                    row.attempted += 1
                # Short timeout: these fixtures resolve in well under a
                # second (local DOM only), so 4s bounds worst case without
                # inflating wall time across N_RUNS.
                result = await page.solve_challenge(timeout=4.0)
                row.observed_statuses.append(result.status)
                if result.status == expected_status:
                    row.matched_expected += 1

                fixture_state = await page._eval(
                    "window.__challenge_state && window.__challenge_state()"
                )
                if result.status == "solved":
                    state_ok = _solved_claim_is_backed(rel_path, fixture_state)
                    if not state_ok:
                        row.false_solved += 1
                        row.notes.append(f"solved claimed but fixture state={fixture_state!r}")
            finally:
                await page.close()
        rows.append(row)
    return rows


def _solved_claim_is_backed(fixture: str, state: object) -> bool:
    """Cross-check a 'solved' status against the fixture's own JS-observed
    state, independent of grip's own token/DOM check. A 'solved' claim that
    disagrees with what the fixture recorded is the exact failure mode this
    benchmark exists to catch."""
    if not isinstance(state, dict):
        # Fixtures that remove the widget on success (sliders) legitimately
        # have no state object left to query.
        return "never" not in fixture
    if "click_seen" in state:
        return bool(state.get("click_seen")) and bool(state.get("token"))
    if "verified" in state:
        return bool(state.get("verified"))
    return True


# --------------------------------------------------------------------------
# Turnstile: real widget, Cloudflare's own test sitekeys, capped run count.
# --------------------------------------------------------------------------


def _turnstile_page(sitekey: str) -> str:
    return f"""<!doctype html>
<html><head><meta charset="utf-8"></head><body>
<h1>Turnstile test</h1>
<div class="cf-turnstile" data-sitekey="{sitekey}"></div>
<script src="https://challenges.cloudflare.com/turnstile/v0/api.js" async defer></script>
</body></html>"""


async def run_turnstile_live() -> list[SolveRow]:
    """3 runs against the always-passes key, 3 against the always-fails key.
    Both are Cloudflare's own published test sitekeys, intended for exactly
    this. Capped, sequential, no retries.

    Both test keys, observed: Cloudflare's widget renders with NO iframe for
    either key — the response token is written straight into a hidden
    `input[name="cf-turnstile-response"]` (pre-filled for always-passes,
    left empty for always-fails), never behind a clickable anchor iframe.
    grip's POINT_PROBE_JS only looks for that iframe, so both cases end
    "unsupported" rather than "solved"/"timeout" — expected_status below
    records what an interactive production Turnstile widget would need
    (click -> token), and `token_present` records the ground truth this
    corpus can actually check: whether Cloudflare had already written a
    token before grip did anything. A "solved" claim with token_present
    False would be the interesting failure; that is what false_solved
    tracks here.
    """
    rows: list[SolveRow] = []
    cases = [
        (TURNSTILE_ALWAYS_PASSES, "always-passes", "solved"),
        (TURNSTILE_ALWAYS_FAILS, "always-fails", "timeout"),
    ]
    for sitekey, label, expected_status in cases:
        row = SolveRow(
            fixture=f"turnstile-{label}",
            source="real-widget(cloudflare-test-key)",
            expected_status=expected_status,
        )
        html = _turnstile_page(sitekey).encode()
        httpd, url = _serve_bytes(html)
        try:
            async with Browser(headless=True, allow_private=True) as browser:
                for _ in range(3):
                    row.runs += 1
                    page = await browser.open(url)
                    try:
                        # Real network load of the Turnstile script + widget
                        # render takes longer than a local fixture.
                        await asyncio.sleep(3.0)
                        token_present = await page._eval(
                            "(function(){var el=document.querySelector("
                            "'[name=\"cf-turnstile-response\"]'); "
                            "return !!(el && el.value);})()"
                        )
                        row.notes.append(f"token_present_before_solve={token_present!r}")
                        stage = await page.detect_challenge()
                        if stage is ChallengeStage.TURNSTILE:
                            row.attempted += 1
                            result = await page.solve_challenge(timeout=15.0)
                            if result.status == "solved" and not token_present:
                                row.false_solved += 1
                        else:
                            result = None
                            row.notes.append(
                                f"classified as {stage.value}, not TURNSTILE; not attempted"
                            )
                        status = result.status if result else stage.value
                        row.observed_statuses.append(status)
                        if status == expected_status:
                            row.matched_expected += 1
                    except Exception as exc:
                        row.observed_statuses.append(f"error:{exc}")
                        row.notes.append(str(exc))
                    finally:
                        await page.close()
                    await asyncio.sleep(1.0)  # be polite between live runs
        finally:
            httpd.shutdown()
        rows.append(row)
    return rows


def _serve_bytes(payload: bytes) -> tuple[http.server.HTTPServer, str]:
    class _Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self) -> None:
            self.send_response(200)
            self.send_header("Content-Type", "text/html")
            self.send_header("Content-Length", str(len(payload)))
            self.end_headers()
            self.wfile.write(payload)

        def log_message(self, fmt: str, *args: object) -> None:
            pass

    httpd = http.server.HTTPServer(("127.0.0.1", 0), _Handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd, f"http://127.0.0.1:{httpd.server_port}"


# --------------------------------------------------------------------------
# Reporting
# --------------------------------------------------------------------------


def _print_classification_table(rows: list[ClassifyRow]) -> None:
    print("\n## Classification (synthetic fixtures)\n")
    header = f"{'fixture':38s} {'expected':10s} {'pure_fn':9s} {'via page()':10s} {'runs':5s}"
    print(header)
    print("-" * len(header))
    for r in rows:
        pf = f"{r.pure_fn_correct}/{r.runs}"
        pg = f"{r.page_correct}/{r.runs}"
        print(f"{r.fixture:38s} {r.expected:10s} {pf:9s} {pg:10s} {r.runs:5d}")


def _print_solve_table(rows: list[SolveRow]) -> None:
    print("\n## Solve rate\n")
    header = (
        f"{'fixture':32s} {'source':30s} {'expected':10s} {'runs':5s} "
        f"{'attempted':10s} {'matched':8s} {'false_solved':13s}"
    )
    print(header)
    print("-" * len(header))
    for r in rows:
        print(
            f"{r.fixture:32s} {r.source:30s} {r.expected_status:10s} {r.runs:5d} "
            f"{r.attempted:10d} {r.matched_expected:8d} {r.false_solved:13d}"
        )
        if r.notes:
            for note in r.notes:
                print(f"    note: {note}")


def _write_json(tag: str, classify_rows: list[ClassifyRow], solve_rows: list[SolveRow],
                 turnstile_rows: list[SolveRow]) -> Path:
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    payload = {
        "generated_at": datetime.now(UTC).isoformat(),
        "n_runs_per_fixture": N_RUNS,
        "classification": [vars(r) for r in classify_rows],
        "solve_synthetic": [vars(r) for r in solve_rows],
        "solve_turnstile_live": [vars(r) for r in turnstile_rows],
        "caveats": [
            "Synthetic fixtures live in this repo and decide their own pass/fail; "
            "they measure whether grip finds the right target and dispatches the "
            "right interaction against markup this corpus controls, not whether "
            "grip defeats any real anti-bot scoring backend.",
            "Turnstile rows use Cloudflare's own published test sitekeys "
            "(1x00000000000000000000AA / 2x00000000000000000000AB), a handful "
            "of runs, no loops or retries against the live service.",
        ],
    }
    out = RESULTS_DIR / f"summary_{tag}.json"
    out.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return out


async def main() -> None:
    print(__doc__)
    tag = _now_tag()

    server = FixtureServer(FIXTURES_DIR)
    base_url = server.start()
    try:
        async with Browser(headless=True, allow_private=True) as browser:
            t0 = time.monotonic()
            classify_rows = await run_classification(browser, base_url)
            solve_rows = await run_solve(browser, base_url)
            dt = time.monotonic() - t0
    finally:
        server.stop()

    turnstile_rows = await run_turnstile_live()

    _print_classification_table(classify_rows)
    _print_solve_table(turnstile_rows)  # print turnstile with the same table shape
    _print_solve_table(solve_rows)

    total_neg = sum(r.runs for r in classify_rows if r.fixture in NEGATIVE_FIXTURES)
    total_neg_fp = sum(
        r.runs - r.page_correct for r in classify_rows if r.fixture in NEGATIVE_FIXTURES
    )
    print(f"\nClassification wall time: {dt:.1f}s")
    print(f"False-positive rate on negative fixtures (via page()): {total_neg_fp}/{total_neg}")

    out_path = _write_json(tag, classify_rows, solve_rows, turnstile_rows)
    print(f"\nWrote {out_path}")


if __name__ == "__main__":
    asyncio.run(main())
