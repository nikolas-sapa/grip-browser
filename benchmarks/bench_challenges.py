"""
Measures grip/challenge.py against the fixtures in
benchmarks/corpus/challenges/fixtures/ (generated by
corpus/challenges/generate_challenge_fixtures.py) plus, for Turnstile, real
widgets served from challenges.cloudflare.com under Cloudflare's own published
test sitekeys.

What this measures, and what it does not
------------------------------------------
1. CLASSIFICATION accuracy of detect_challenge_from_html — both directly
   (pure function, no browser) and through page.detect_challenge() on a
   served fixture (proves the frame-tree/DOM plumbing agrees with the pure
   function), including negative fixtures so false positives are counted,
   not just recall.
2. SOLVE rate for the stages grip attempts in-process (checkbox, slider
   locally; Turnstile against the real widget) — specifically whether a
   "solved" claim is ever made when the fixture's own JS did NOT grant a
   token / remove the widget. That is the false-solved probe; see
   solve_checkbox_never.html and solve_slider_never.html.

Every synthetic fixture lives in this repo and grants or withholds its own
token — it measures whether grip finds the right target and dispatches the
right interaction against markup this corpus controls. It does NOT measure
whether grip defeats any real anti-bot scoring backend, because no real
backend is involved. That claim is only meaningful for the labelled
real-widget (Cloudflare Turnstile test key) rows below, and even those use
Cloudflare's own test keys, not a production key protecting a resource grip
does not own.

No live third-party target is loaded more than a handful of times. No loops,
no retries against a live host.

Run: .venv/bin/python benchmarks/bench_challenges.py
"""
from __future__ import annotations

import asyncio
import http.server
import json
import re
import socket
import threading
import time
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path

from grip.browser import Browser
from grip.challenge import ChallengeStage, detect_challenge_from_html

FIXTURES_DIR = Path(__file__).parent / "corpus" / "challenges" / "fixtures"
RESULTS_DIR = Path(__file__).parent / "corpus" / "challenges" / "results"
N_RUNS = 5

# --------------------------------------------------------------------------
# Fixture server (stdlib, same pattern as bench_llm_loop.FixtureServer)
# --------------------------------------------------------------------------


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class _QuietHandler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, fmt: str, *args: object) -> None:
        pass


class FixtureServer:
    def __init__(self, directory: Path) -> None:
        self.port = _free_port()
        handler = lambda *a, **kw: _QuietHandler(*a, directory=str(directory), **kw)  # noqa: E731
        self._httpd = http.server.ThreadingHTTPServer(("127.0.0.1", self.port), handler)
        self._thread = threading.Thread(target=self._httpd.serve_forever, daemon=True)

    def start(self) -> str:
        self._thread.start()
        return f"http://127.0.0.1:{self.port}"

    def stop(self) -> None:
        self._httpd.shutdown()
        self._httpd.server_close()


